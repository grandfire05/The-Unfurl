  function make(c) {
    const grade = typeof c === 'string' ? c : c.grade;
    const info = typeof c === 'string' ? {} : c;
    const out = [];
    const fam = raceFamily(info.appearance);
    out.push(fam && Math.random() < 0.55 ? pick(RACE_LINES[fam]) : pick(ORIGIN));
    out.push(pick(PAST));
    const sources = [];
    if (info.path && CLASS_LINES[info.path[0]]) sources.push(() => pick(CLASS_LINES[info.path[0]]));
    if (info.split) sources.push(() => pick(STAT_LINES[argmax(info.split)]));
    if (info.traits && info.traits.length) sources.push(() => pick(TRAIT_LINES[traitCat(pick(info.traits))]), () => pick(TRAIT_LINES[traitCat(pick(info.traits))]));
    out.push(sources.length ? pick(sources)() : pick(SHARED));
    const r = Math.random();
    if (info.mainAttribute && r < 0.62) out.push(pick(ATTR_LINES[info.mainAttribute]));
    else if (info.subAttribute && r < 0.78) out.push(pick(SUB_LINES[info.subAttribute]));
    else out.push(pick(FLAVOR[tierOf(grade)]));
    return out;
  }
