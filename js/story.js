  function variants(info) {
    const fam = raceFamily(info.appearance);
    const l1 = new Set(ORIGIN.concat(fam ? RACE_LINES[fam] : [])).size;
    const l2 = new Set(PAST).size;
    const l3 = new Set([].concat(CLASS_LINES[(info.path || [])[0]] || [], STAT_LINES[argmax(info.split || [1, 0, 0, 0, 0])], ...(info.traits || []).map((n) => TRAIT_LINES[traitCat(n)]))).size;
    const l4 = new Set([].concat(ATTR_LINES[info.mainAttribute] || [], info.subAttribute ? SUB_LINES[info.subAttribute] : [], FLAVOR[tierOf(info.grade)])).size;
    return l1 * l2 * l3 * l4;
  }

